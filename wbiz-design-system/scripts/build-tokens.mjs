// Regenerates src/styles/tokens.css and src/styles/theme.css from tokens/tokens.json.
// Run with `npm run tokens`.
import { writeFileSync } from 'node:fs';
import { cssVariables, themeCss } from '../tokens/index.mjs';

const header = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n`;
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), header + cssVariables());
writeFileSync(new URL('../src/styles/theme.css', import.meta.url), header + themeCss());
console.log('Wrote src/styles/tokens.css and src/styles/theme.css');

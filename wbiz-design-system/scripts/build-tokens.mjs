// Regenerates src/styles/tokens.css from tokens/tokens.json. Run with `npm run tokens`.
import { writeFileSync } from 'node:fs';
import { cssVariables } from '../tokens/index.mjs';

const header = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n`;
const out = new URL('../src/styles/tokens.css', import.meta.url);
writeFileSync(out, header + cssVariables());
console.log('Wrote src/styles/tokens.css');

// Rebuilds the iBroka wordmark as vector paths from Instrument Sans Bold.
// Output: public/*.svg (Storybook brand, favicon) and src/components/logo-paths.ts (Logo component).
// Run: node scripts/build-logo.mjs
import opentype from 'opentype.js';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const buf = fs.readFileSync(path.join(root, 'node_modules/@fontsource/instrument-sans/files/instrument-sans-latin-700-normal.woff'));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const SIZE = 100;
const pad = 2;
const f = (n) => Number(n.toFixed(2));

const word = font.getPath('ıBroka', 0, 0, SIZE); // dotless i, the dot is drawn in brand teal
const wb = word.getBoundingBox();
const iBox = font.getPath('i', 0, 0, SIZE).getBoundingBox();
const stem = font.getPath('ı', 0, 0, SIZE);
const sb = stem.getBoundingBox();
const gapTop = sb.y1 - 6;
const dot = { cx: f((sb.x1 + sb.x2) / 2), cy: f((iBox.y1 + gapTop) / 2), r: f(((gapTop - iBox.y1) / 2) * 1.05) };

const box = (b) => {
  const x = Math.min(b.x1, dot.cx - dot.r) - pad;
  const y = Math.min(b.y1, dot.cy - dot.r) - pad;
  return [f(x), f(y), f(Math.max(b.x2, dot.cx + dot.r) - x + pad), f(b.y2 - y + pad)];
};
const wordBox = box(wb);
const markBox = box(sb);
const wordD = word.toPathData(2);
const stemD = stem.toPathData(2);

const svg = (vb, d, ink, dotFill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(' ')}" role="img" aria-label="iBroka"><path fill="${ink}" d="${d}"/><circle fill="${dotFill}" cx="${dot.cx}" cy="${dot.cy}" r="${dot.r}"/></svg>\n`;

fs.writeFileSync(path.join(root, 'public/ibroka-logo.svg'), svg(wordBox, wordD, '#272728', '#36A59E'));
fs.writeFileSync(path.join(root, 'public/ibroka-logo-inverse.svg'), svg(wordBox, wordD, '#FFFFFF', '#3FB8B0'));
fs.writeFileSync(path.join(root, 'public/ibroka-mark.svg'), svg(markBox, stemD, '#272728', '#36A59E'));

const S = 64;
const scale = 40 / markBox[3];
const tx = S / 2 - (markBox[0] + markBox[2] / 2) * scale;
const ty = S / 2 - (markBox[1] + markBox[3] / 2) * scale;
fs.writeFileSync(
  path.join(root, 'public/favicon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}"><rect width="${S}" height="${S}" rx="14" fill="#247A75"/><g transform="translate(${f(tx)} ${f(ty)}) scale(${scale.toFixed(4)})" fill="#FFFFFF"><path d="${stemD}"/><circle cx="${dot.cx}" cy="${dot.cy}" r="${dot.r}"/></g></svg>\n`,
);

fs.writeFileSync(
  path.join(root, 'src/components/logo-paths.ts'),
  `// Generated by scripts/build-logo.mjs from Instrument Sans Bold. Do not edit by hand.\n` +
    `export const WORD_VIEWBOX = '${wordBox.join(' ')}';\n` +
    `export const MARK_VIEWBOX = '${markBox.join(' ')}';\n` +
    `export const WORD_PATH = '${wordD}';\n` +
    `export const MARK_PATH = '${stemD}';\n` +
    `export const DOT = ${JSON.stringify(dot)} as const;\n`,
);
console.log('logo written', wordBox, markBox, dot);

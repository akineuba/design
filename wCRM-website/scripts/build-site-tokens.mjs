// Generates src/styles/site-tokens.css from tokens/site-tokens.json (the website-only extension of the
// wCRM design-system tokens). Run `npm run tokens` after editing the JSON; `--check` fails when stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens/site-tokens.json'), 'utf8'));
const key = (k) => k.replace(/\./g, '_');
const lines = [];
const darkLines = [];
const add = (name, value, dark) => {
  lines.push(`  --${name}: ${value};`);
  if (dark !== undefined) darkLines.push(`  --${name}: ${dark};`);
};

for (const [group, entries] of Object.entries(tokens.color))
  for (const [name, t] of Object.entries(entries)) add(`color-${group}-${name}`, t.value, t.dark);
for (const [name, t] of Object.entries(tokens.font.family)) add(`font-${name}`, t.value);
for (const [name, t] of Object.entries(tokens.typography)) {
  add(`text-${name}-size`, t.size);
  add(`text-${name}-line-height`, t.lineHeight);
  add(`text-${name}-weight`, t.weight);
}
for (const [name, t] of Object.entries(tokens.lineHeight)) add(`leading-${key(name)}`, t.value);
for (const [name, t] of Object.entries(tokens.space)) add(`space-${key(name)}`, t.value);
for (const [name, t] of Object.entries(tokens.radius)) add(`radius-${key(name)}`, t.value);
for (const [name, t] of Object.entries(tokens.size)) add(`size-${name}`, t.value);
for (const [name, t] of Object.entries(tokens.shadow)) add(`shadow-${name}`, t.value);
for (const [name, t] of Object.entries(tokens.gradient)) add(`gradient-${name}`, t.value);
for (const [name, t] of Object.entries(tokens.scale)) add(`scale-${name}`, t.value);

const css =
  `/* Generated by scripts/build-site-tokens.mjs from tokens/site-tokens.json. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n\n` +
  `[data-theme='dark'],\n.dark {\n${darkLines.join('\n')}\n}\n`;
const out = resolve(root, 'src/styles/site-tokens.css');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (current !== css) { console.error('src/styles/site-tokens.css is stale: run `npm run tokens`.'); process.exit(1); }
  console.log('Site tokens are up to date.');
} else {
  writeFileSync(out, css);
  console.log(`Wrote ${lines.length} variables to src/styles/site-tokens.css`);
}
